export function byId(id) {
  return songs.find((s) => s.id === id);
}

// Sibling versions of the same song, like the "More versions" rail.
export function versionsOf(song) {
  return songs.filter(
    (s) => s.title === song.title && s.type === song.type && s.id !== song.id,
  );
}
